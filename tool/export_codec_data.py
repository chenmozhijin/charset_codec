def _format_generated_rust(paths: list[Path]) -> str:
    rustfmt = shutil.which("rustfmt")
    if rustfmt is None:
        raise RuntimeError("rustfmt is required to generate native Rust assets")
    # The manifest must record rustfmt's final bytes; otherwise the format gate
    # makes the generated hashes permanently drift.
    for path in paths:
        subprocess.run(
            [rustfmt, "--edition", "2024", str(path)],
            cwd=ROOT / "native",
            check=True,
        )
    completed = subprocess.run(
        [rustfmt, "--version"],
        cwd=ROOT / "native",
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()
